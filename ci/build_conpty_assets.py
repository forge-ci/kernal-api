#!/usr/bin/env python3
"""Build the reproducible ConPTY sidecar archives and their sha256 manifest.

Usage: ``python ci/build_conpty_assets.py [<output-dir>]``
(default ``target/conpty-assets``). ``SOURCE_DATE_EPOCH`` sets archive mtimes.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ARCHES = ("x64", "arm64", "x86")
INPUTS = ("conpty.dll", "OpenConsole.exe")
LFS_POINTER = b"version https://git-lfs.github.com/spec/v1"
MANIFEST_NAME = "conpty-sidecar.sha256.toml"
HEADER = (
    "# Generated by ci/build_conpty_assets.py. Release automation regenerates and\n"
    "# compares this fail-closed manifest before publishing the crate.\n\n"
)


class AssetError(RuntimeError):
    """A required input is missing or a tool failed."""


@dataclass(frozen=True)
class Asset:
    arch: str
    sha256: str
    size_bytes: int


def package_version(repo: Path) -> str:
    for line in (repo / "WINDOWS_CONPTY_VERSION.txt").read_text(encoding="utf-8").splitlines():
        fields = line.split()
        if len(fields) >= 2 and fields[0] == "Microsoft.Windows.Console.ConPTY":
            return fields[1]
    raise AssetError("WINDOWS_CONPTY_VERSION.txt has no package version")


def check_input(path: Path) -> None:
    if not path.is_file() or path.stat().st_size == 0:
        raise AssetError(f"required ConPTY input is absent or empty: {path}")
    with path.open("rb") as handle:
        if LFS_POINTER in handle.read(64):
            raise AssetError(f"required ConPTY input is an unresolved Git LFS pointer: {path}")


def pack(stage: Path, archive: Path, epoch: str) -> None:
    """`tar ... | zstd -19 -T1`, byte-identical to the former shell pipeline."""
    tar = subprocess.Popen(
        [
            "tar",
            "--sort=name",
            f"--mtime=@{epoch}",
            "--owner=0",
            "--group=0",
            "--numeric-owner",
            "-cf",
            "-",
            "-C",
            str(stage),
            ".",
        ],
        stdout=subprocess.PIPE,
    )
    assert tar.stdout is not None
    zstd = subprocess.run(["zstd", "-q", "-19", "-T1", "-f", "-o", str(archive)], stdin=tar.stdout, check=False)
    tar.stdout.close()
    if tar.wait() != 0 or zstd.returncode != 0:
        raise AssetError(f"packing {archive} failed (tar {tar.returncode}, zstd {zstd.returncode})")


def build_asset(repo: Path, output_dir: Path, arch: str, version: str, epoch: str) -> Asset:
    source_dir = repo / "vendor" / "win32" / "conpty" / arch
    for name in INPUTS:
        check_input(source_dir / name)
    stage = output_dir / f"stage-{arch}"
    shutil.rmtree(stage, ignore_errors=True)
    stage.mkdir(parents=True)
    for name in INPUTS:
        shutil.copyfile(source_dir / name, stage / name)
    (stage / "VERSION.txt").write_text(f"{version}\n", encoding="utf-8", newline="\n")
    archive = output_dir / f"conpty-sidecar-{arch}.tar.zst"
    pack(stage, archive, epoch)
    data = archive.read_bytes()
    return Asset(arch=arch, sha256=hashlib.sha256(data).hexdigest(), size_bytes=len(data))


def render(assets: list[Asset]) -> str:
    body = "".join(
        f'[asset.{asset.arch}]\nsha256 = "{asset.sha256}"\nsize_bytes = {asset.size_bytes}\n\n' for asset in assets
    )
    return HEADER + body


def main(argv: list[str]) -> int:
    output_dir = Path(argv[0]) if argv else REPO / "target" / "conpty-assets"
    epoch = os.environ.get("SOURCE_DATE_EPOCH") or "0"
    try:
        version = package_version(REPO)
        output_dir.mkdir(parents=True, exist_ok=True)
        assets = [build_asset(REPO, output_dir, arch, version, epoch) for arch in ARCHES]
    except AssetError as error:
        print(error, file=sys.stderr)
        return 1
    manifest = output_dir / MANIFEST_NAME
    manifest.write_text(render(assets), encoding="utf-8", newline="\n")
    for stage in output_dir.glob("stage-*"):
        shutil.rmtree(stage)
    print(f"wrote {manifest}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
